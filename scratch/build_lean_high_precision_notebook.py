    "### 3. Lean Multi-Key Inverted Index (< 1.2 GB RAM)\n",
    "Instead of allocating billions of floats in memory, this inverted index maps lightweight hash keys to candidate IDs in Python memory. Total RAM consumed per country is **under 1.2 GB**."
