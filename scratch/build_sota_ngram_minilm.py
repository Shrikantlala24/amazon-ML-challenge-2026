    "class MemorySafeTFIDFEngine:\n",
    "    def __init__(self, max_candidates=6, min_cosine_threshold=0.35):\n",
    "        self.vectorizer = TfidfVectorizer(\n",
    "            analyzer='char_wb',\n",
    "            ngram_range=(3, 3),\n",
    "            min_df=2,\n",
    "            max_features=40000,\n",
    "            sublinear_tf=True,\n",
    "            dtype=np.float32\n",
    "        )\n",
    "        self.max_candidates = max_candidates\n",
    "        self.min_cosine = min_cosine_threshold\n",
    "        self.candidate_ids = []\n",
    "        self.records = {}\n",
    "        self.cand_matrix = None\n",
    "\n",
    "    def fit_candidates(self, df_cands):\n",
    "        self.candidate_ids = df_cands['entity_id'].tolist()\n",
    "        texts = []\n",
    "        for _, row in df_cands.iterrows():\n",
    "            eid = row['entity_id']\n",
    "            raw_name = row['business_name']\n",
    "            raw_addr = row['business_address']\n",
    "            c_name = clean_name(raw_name)\n",
    "            c_addr = clean_address(raw_addr)\n",
    "            nums = extract_numbers(raw_addr)\n",
    "            tag = extract_legal_tag(raw_name)\n",
    "            \n",
    "            self.records[eid] = (raw_name, c_name, tag, raw_addr, c_addr, nums)\n",
    "            texts.append(f\"{c_name} {c_name} {c_addr}\")\n",
    "\n",
    "        self.cand_matrix = self.vectorizer.fit_transform(texts)\n",
    "        self.cand_matrix = sparse.csr_matrix(self.cand_matrix, dtype=np.float32)\n",
    "\n",
    "    def query_batch_chunked(self, s1_texts_batch, batch_s1_ids, chunk_size=1000):\n",
    "        \"\"\"Processes queries in 1,000-row micro-chunks to strictly control RAM.\"\"\"\n",
    "        s1_matrix = self.vectorizer.transform(s1_texts_batch)\n",
    "        results = {}\n",
    "        num_queries = s1_matrix.shape[0]\n",
    "        cand_matrix_T = self.cand_matrix.T\n",
    "        \n",
    "        for start in range(0, num_queries, chunk_size):\n",
    "            end = min(start + chunk_size, num_queries)\n",
    "            sub_s1 = s1_matrix[start:end]\n",
    "            sim_sub = sub_s1.dot(cand_matrix_T)\n",
    "            \n",
    "            for i in range(sim_sub.shape[0]):\n",
    "                s1_id = batch_s1_ids[start + i]\n",
    "                row = sim_sub.getrow(i)\n",
    "                if row.nnz == 0:\n",
    "                    results[s1_id] = []\n",
    "                    continue\n",
    "                \n",
    "                cols = row.indices\n",
    "                vals = row.data\n",
    "                valid = vals >= self.min_cosine\n",
    "                if not np.any(valid):\n",
    "                    best_idx = cols[np.argmax(vals)]\n",
    "                    results[s1_id] = [(self.candidate_ids[best_idx], float(np.max(vals)))]\n",
    "                    continue\n",
    "                    \n",
    "                f_cols = cols[valid]\n",
    "                f_vals = vals[valid]\n",
    "                top_order = np.argsort(-f_vals)[:self.max_candidates]\n",
    "                results[s1_id] = [(self.candidate_ids[f_cols[idx]], float(f_vals[idx])) for idx in top_order]\n",
    "                \n",
    "            del sim_sub\n",
    "            \n",
    "        return results\n",
    "\n",
    "print(\"MemorySafeTFIDFEngine defined.\")"
