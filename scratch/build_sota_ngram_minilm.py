    "To prevent Colab RAM crashes:\n",
    "* Uses `dtype=np.float32` and `max_features=40000`.\n",
    "* Queries in **micro-chunks of 1,000 rows** (`sub_batch_size=1000`).\n",
    "* Memory per query chunk is **under 300 MB**, keeping total RAM well under 1.5 GB at all times."
