    "def get_char_3grams(text):\n",
    "    text = f\" {text} \"\n",
    "    if len(text) < 3:\n",
    "        return {text}\n",
    "    return {text[i:i+3] for i in range(len(text)-2)}\n",
    "\n",
    "class FastNGramInvertedIndex:\n",
    "    def __init__(self, max_candidates=6):\n",
    "        self.ngram_index = defaultdict(list)\n",
    "        self.ngram_counts = Counter()\n",
    "        self.records = {}\n",
    "        self.max_candidates = max_candidates\n",
    "        \n",
    "    def add_records(self, df_cands):\n",
    "        for _, row in df_cands.iterrows():\n",
    "            eid = row['entity_id']\n",
    "            raw_name = row['business_name']\n",
    "            raw_addr = row['business_address']\n",
    "            c_name = clean_name(raw_name)\n",
    "            c_addr = clean_address(raw_addr)\n",
    "            nums = extract_numbers(raw_addr)\n",
    "            tag = extract_legal_tag(raw_name)\n",
    "            \n",
    "            self.records[eid] = (raw_name, c_name, tag, raw_addr, c_addr, nums)\n",
    "            \n",
    "            # Extract 3-grams from name (primary) + address numbers\n",
    "            ngs = get_char_3grams(c_name)\n",
    "            for n in nums:\n",
    "                ngs.add(f\"#{n}\")\n",
    "                \n",
    "            for ng in ngs:\n",
    "                self.ngram_index[ng].append(eid)\n",
    "                self.ngram_counts[ng] += 1\n",
    "\n",
    "    def get_candidates(self, c_name, nums):\n",
    "        q_ngs = get_char_3grams(c_name)\n",
    "        for n in nums:\n",
    "            q_ngs.add(f\"#{n}\")\n",
    "            \n",
    "        candidate_scores = Counter()\n",
    "        for ng in q_ngs:\n",
    "            # Skip ultra-common n-grams (>20,000 occurrences) to save time and filter noise\n",
    "            if self.ngram_counts[ng] > 20000:\n",
    "                continue\n",
    "            for cid in self.ngram_index.get(ng, []):\n",
    "                candidate_scores[cid] += 1\n",
    "                \n",
    "        if not candidate_scores:\n",
    "            return []\n",
    "            \n",
    "        # Return top K candidates sorted by character n-gram overlap\n",
    "        return [cid for cid, _ in candidate_scores.most_common(self.max_candidates)]\n",
    "\n",
    "print(\"FastNGramInvertedIndex ready.\")"
